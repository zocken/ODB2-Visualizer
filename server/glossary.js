// Tokens, die unverändert bleiben dürfen (Buchstaben-/Zahlenkennungen, Fachkürzel).
export const PASSTHROUGH = /^([A-Z]|\d+|\d+-\d+|[A-L]\d?|B\dS\d|#\d+|Bank|CAN|ABS|DC|AC|EV|LIN|IPC|SRS|PWM|VIN|ID|\+|-|–|&|[A-H]\/[A-H])$/i;
// Herstellerkürzel (z. B. BBV, EBTCM, VTEC) und Kennungen mit Ziffern (J1850, PDS1, 1.8L, 24X) bleiben stehen.
const ABBREVIATION = /^([A-Z][A-Z0-9-]{1,5}|[A-Za-z]*\d[A-Za-z0-9.#]*)$/;

const entries = Object.entries(PHRASES)
  .map(([en, de]) => [en.toLowerCase().split(/\s+/), de])
  .sort((a, b) => b[0].length - a[0].length);
const MAX_WORDS = Math.max(...entries.map(([w]) => w.length));
const lookup = new Map(entries.map(([w, de]) => [w.join(' '), de]));

function translateWords(text) {
  const tokens = text.split(/(\s+|\(|\)|,)/).filter((t) => t !== '' && !/^\s+$/.test(t));
  const out = [];
  let missing = 0;
  for (let i = 0; i < tokens.length;) {
    let matched = false;
    for (let n = Math.min(MAX_WORDS, tokens.length - i); n > 0; n--) {
      const key = tokens.slice(i, i + n).join(' ').toLowerCase();
      if (lookup.has(key)) { out.push(lookup.get(key)); i += n; matched = true; break; }
    }
    if (matched) continue;
    const token = tokens[i++];
    if (PASSTHROUGH.test(token) || ABBREVIATION.test(token) || /^[()+,\/-]$/.test(token)) { out.push(token); continue; }
    // Kombinierte Begriffe wie "Circuit/Open" oder "Range/Performance" teilweise übersetzen.
    if (token.includes('/')) {
      const parts = token.split('/').map((p) => translateWords(p));
      if (parts.every((p) => p.missing === 0)) { out.push(parts.map((p) => p.text).join('/')); continue; }
    }
    out.push(token); missing++;
  }
  const text2 = out.join(' ').replace(/\( /g, '(').replace(/ \)/g, ')').replace(/ ,/g, ',').replace(/\s+/g, ' ').trim()
    .replace(/Steuerung Stromkreis/g, 'Steuerstromkreis')
    .replace(/Stromkreis\/Unterbrechung/g, 'Stromkreis unterbrochen');
  return { text: text2, missing };
}

// Liefert { text, complete }. complete=false heißt: nicht alle Wörter waren im Glossar.
export function translateTitle(en) {
  const clean = en.replace(/\s+–\s+/g, ' - ').replace(/\s+/g, ' ').trim();
  let m = clean.match(/^Lost Communication With (.+)$/i);
  if (m) { const t = translateWords(m[1]); return { text: `Kommunikation mit ${t.text} verloren`, complete: t.missing === 0 }; }
  m = clean.match(/^Invalid Data Received From (.+)$/i);
  if (m) { const t = translateWords(m[1]); return { text: `Ungültige Daten von ${t.text} empfangen`, complete: t.missing === 0 }; }
  const t = translateWords(clean);
  return { text: t.text.charAt(0).toUpperCase() + t.text.slice(1), complete: t.missing === 0 };
}

export function untranslatedWords(en) {
  return en.split(/[\s()\/,]+/).filter((w) => w && !PASSTHROUGH.test(w) && !ABBREVIATION.test(w) && !lookup.has(w.toLowerCase()));
}
